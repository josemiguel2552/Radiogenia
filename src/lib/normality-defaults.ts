const NUMBERED_LABEL = /^\d+\.\s/;

function shouldSkip(label: string): boolean {
  const lower = label.toLowerCase();
  if (SKIP_LABELS.has(lower)) return true;
  if (NUMBERED_LABEL.test(label)) return true;
  return false;
}

export function extractSectionsFromTemplates(): { modality: string; label: string }[] {
  const seen = new Set<string>();
  const result: { modality: string; label: string }[] = [];

  for (const t of DEFAULT_TEMPLATES) {
    if (t.technique === "Procedures") continue;
    const re = /\*{2,3}([^*]+)\*{2,3}(?::?\s*\{[^}]+\})/g;
    let m;
    while ((m = re.exec(t.template)) !== null) {
      const label = m[1].trim();
      if (shouldSkip(label)) continue;
      const key = `${t.technique}|${label.toLowerCase()}`;
      if (seen.has(key)) continue;
      seen.add(key);
      result.push({ modality: t.technique, label });
    }
  }

  result.sort((a, b) => a.modality.localeCompare(b.modality) || a.label.localeCompare(b.label));
  return result;
}

