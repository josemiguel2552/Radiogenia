export type NormalityLang = "en" | "es";

export function getDefaultPhrase(modality: string, sectionLabel: string, lang: NormalityLang = "en"): string {
  if (lang === "es") {
    return DEFAULTS_ES[modality]?.[sectionLabel]
      ?? MODALITY_GENERIC.es[modality]
      ?? "Sin alteraciones significativas.";
  }
  return DEFAULTS[modality]?.[sectionLabel]
    ?? MODALITY_GENERIC.en[modality]
    ?? "No significant abnormalities.";
}

export function getAllDefaults(lang: NormalityLang = "en"): NormalityDefault[] {
  const sections = extractSectionsFromTemplates();
  return sections.map(({ modality, label }) => ({
    modality,
    section_label: label,
    phrase: getDefaultPhrase(modality, label, lang),
  }));
}

export function getDefaultsForModality(modality: string, lang: NormalityLang = "en"): NormalityDefault[] {
  return getAllDefaults(lang).filter((d) => d.modality === modality);
}
