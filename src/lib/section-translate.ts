export function enforcePeriodSeparation(text: string): string {
  if (!text) return text;
  return text.replace(/^([^:\n]+:\s*)(.+)$/gm, (_match, prefix: string, desc: string) => {
    let fixed = desc.replace(/;\s*/g, ". ");
    fixed = fixed.replace(/,\s+(?=[A-ZÁÉÍÓÚÑÀÈÌÒÙÂÊÎÔÛÃÕÇ])/g, ". ");
    if (fixed !== desc) {
      fixed = fixed.replace(/\.\s*\./g, ".");
    }
    return prefix + fixed;
  });
}

export function mergeDuplicateSections(text: string): string {
  if (!text) return text;
  const lines = text.split("\n");
  const seen = new Map<string, number>();
  const result: string[] = [];

  for (const line of lines) {
    const colonIdx = line.indexOf(":");
    if (colonIdx === -1) { result.push(line); continue; }

    const label = line.slice(0, colonIdx).trim().toLowerCase();
    const content = line.slice(colonIdx + 1).trim();

    if (seen.has(label)) {
      const idx = seen.get(label)!;
      const existing = result[idx];
      const existingColonIdx = existing.indexOf(":");
      const existingContent = existing.slice(existingColonIdx + 1).trim();
      const prefix = existing.slice(0, existingColonIdx + 1);
      const merged = existingContent.endsWith(".")
        ? `${existingContent} ${content}`
        : `${existingContent}. ${content}`;
      result[idx] = `${prefix} ${merged}`;
    } else {
      seen.set(label, result.length);
      result.push(line);
    }
  }

  return result.join("\n");
}

// ---------------------------------------------------------------------------
// Safety net: fill or strip unfilled template placeholders
// ---------------------------------------------------------------------------
// Template fields are injected as "**Label**: {label lowercased}". If the model
// leaves a placeholder unfilled it must NEVER reach the report as a raw
// "{trachea and bronchi}" token. This replaces a whole-line placeholder value
// with the section's normality phrase (matched by the English placeholder
// token), falling back to a generic normal statement, and strips any stray
// leftover token.
const GENERIC_NORMAL: Record<OutputLanguage, string> = {
  es: "Sin alteraciones significativas.",
  en: "No significant abnormality.",
  pt: "Sem alterações significativas.",
};

export function fillTemplatePlaceholders(
  text: string,
  normalByToken: Map<string, string>,
  lang: OutputLanguage,
): string {
  if (!text || text.indexOf("{") === -1) return text;
  const fallback = GENERIC_NORMAL[lang] || GENERIC_NORMAL.en;

  // "Label: {token}"  (the whole value is a bare placeholder)
  let result = text.replace(
    /^([^\n:]+):[ \t]*\{([^{}\n]+)\}[ \t]*$/gm,
    (_m, label: string, token: string) => {
      const phrase = normalByToken.get(token.trim().toLowerCase());
      return `${label}: ${phrase || fallback}`;
    },
  );

  // Any remaining stray placeholder token anywhere → remove it.
  result = result.replace(/\{[^{}\n]+\}/g, "").replace(/[ \t]+$/gm, "");

  return result;
}

export function enforceOutputLanguage(text: string, lang: OutputLanguage): string {
  if (lang === "en" || !text) return text;

  const dict = getDictForLang(lang);
  const phrases = lang === "es" ? NORMALITY_PHRASE_ES : lang === "pt" ? NORMALITY_PHRASE_PT : null;

  let result = text;

  if (dict) {
    result = result.replace(/^([^\n:]+):\s/gm, (match, label: string) => {
      const trimmed = label.trim();
      const translated = dict[trimmed];
      if (translated) return translated + ": ";
      return match;
    });
  }

  if (phrases) {
    for (const [pattern, replacement] of phrases) {
      result = result.replace(pattern, replacement);
    }
  }

  result = enforcePeriodSeparation(result);

  return result;
}
