export function translateSectionLabel(name: string, lang: OutputLanguage): string {
  if (lang === "es") return ES[name] ?? name;
  if (lang === "pt") return PT[name] ?? name;
  return name;
}

/** True if `name` has an explicit entry in the translation dictionary for `lang`. */
export function hasSectionTranslation(name: string, lang: OutputLanguage): boolean {
  if (lang === "es") return name in ES;
  if (lang === "pt") return name in PT;
  return true;
}

function getDictForLang(lang: OutputLanguage): Record<string, string> | null {
  if (lang === "es") return ES;
  if (lang === "pt") return PT;
  return null;
}

export function translateTemplate(template: string, lang: OutputLanguage): string {
  if (lang === "en" || !template) return template;
  const dict = getDictForLang(lang);
  if (!dict) return template;

  return template.replace(
    /(\*{2,3})([^*]+)\1/g,
    (match, stars: string, label: string) => {
      const trimmed = label.trim();
      const translated = dict[trimmed];
      if (!translated) return match;
      return `${stars}${translated}${stars}`;
    },
  );
}

export function translateLabelInLine(line: string, lang: OutputLanguage): string {
  const dict = getDictForLang(lang);
  if (!dict) return line;
  const m = line.match(/^([^:]+):\s/);
  if (!m) return line;
  const label = m[1].trim();
  const translated = dict[label];
  if (!translated) return line;
  return translated + ": " + line.slice(m[0].length);
}

